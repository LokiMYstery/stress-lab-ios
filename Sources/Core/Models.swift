import Foundation

struct DataSource: Codable, Hashable, Identifiable {
    var id: String
    var name: String
    var isAppleWatch: Bool
}

struct Beat: Codable, Equatable {
    var offset: Double
    var precededByGap: Bool
}

struct HeartbeatRecord: Codable, Identifiable {
    var id: String
    var start: Date
    var end: Date
    var sourceID: String
    var beats: [Beat]
}

enum MotionContext: String, Codable { case sedentary, active, unknown }
enum QuantityKind: String, Codable { case heartRate, sdnn, restingHeartRate, steps }
struct QuantityRecord: Codable, Identifiable {
    var id: String
    var start: Date
    var end: Date
    var sourceID: String
    var kind: QuantityKind
    var value: Double
    var motion: MotionContext = .unknown
}

enum IntervalKind: String, Codable { case sleep, awake, workout, mindfulness }
struct ContextInterval: Codable, Identifiable {
    var id: String
    var start: Date
    var end: Date
    var sourceID: String
    var kind: IntervalKind
}

struct HealthDataset: Codable {
    var sources: [DataSource] = []
    var heartbeats: [HeartbeatRecord] = []
    var quantities: [QuantityRecord] = []
    var intervals: [ContextInterval] = []
    var fetchedAt: Date? = nil
    var isDemo: Bool = false
}

struct ExperimentParameters: Codable, Equatable {
    var baselineDays: Int = 30
    var heartRateFreshMinutes: Double = 15
    var hrvLifetimeHours: Double = 1.5
    var slope: Double = 20
    var pressureSlope: Double = 8
    var recoverySlope: Double = 15
    var mappingVersion: Int = 3
    var hrvFilterEnabled: Bool = false
    var redJumpThreshold: Double = 20
    var redCooldownMinutes: Double = 45
    var hrvScoreFloor: Double = 4
    var hrvScoreMidpoint: Double = 50
    var hrvScoreSteepness: Double = 0.155
    // Kept only to reproduce reports generated by historical step-based versions.
    var movementStepWindowMinutes: Double = 10
    var movementStepThreshold: Double = 8
    var useStepMovement: Bool = false
    var restingHRWeight: Double = 0.65
    var restingHRScaleFloor: Double = 5
    var center: Double = 50
    var minIntervalMS: Double = 300
    var maxIntervalMS: Double = 2000
    var minimumDuration: Double = 30
    var minimumPairs: Int = 20
    var minimumDays: Int = 7
    var minimumHRVRecords: Int = 20
    var minimumHRBins: Int = 100
    var hrvScaleFloor: Double = 0.25
    var hrScaleFloor: Double = 8
    var workoutRecoveryMinutes: Double = 30
    // V0 product references for cold-start comparisons, not population norms.
    var defaultRMSSDMS: Double = 50
    var defaultHeartRateBPM: Double = 70
    var defaultHRVScale: Double = 0.5
    var defaultHeartRateScale: Double = 10

    init() {}

    static var legacyV0: ExperimentParameters {
        var value = ExperimentParameters()
        value.mappingVersion = 0
        value.hrvFilterEnabled = true
        value.movementStepWindowMinutes = 10
        value.movementStepThreshold = 8
        value.useStepMovement = true
        value.hrvLifetimeHours = 3
        value.hrvScaleFloor = 0.15
        value.hrScaleFloor = 3
        return value
    }

    static var legacyV1: ExperimentParameters {
        var value = ExperimentParameters()
        value.mappingVersion = 1
        value.hrvFilterEnabled = true
        value.movementStepWindowMinutes = 10
        value.movementStepThreshold = 8
        value.useStepMovement = true
        return value
    }

    static var legacyV2: ExperimentParameters {
        var value = ExperimentParameters()
        value.mappingVersion = 2
        value.movementStepWindowMinutes = 10
        value.movementStepThreshold = 8
        value.useStepMovement = true
        return value
    }

    static var legacyV3: ExperimentParameters {
        var value = ExperimentParameters()
        value.movementStepWindowMinutes = 10
        value.movementStepThreshold = 8
        value.useStepMovement = true
        return value
    }

    func mappedScore(for deviation: Double) -> Int? {
        guard deviation.isFinite else { return nil }
        let appliedSlope = mappingVersion == 0 ? slope : (deviation >= 0 ? pressureSlope : recoverySlope)
        let raw = center + appliedSlope * deviation
        guard raw.isFinite else { return nil }
        return Int(min(100, max(1, raw.rounded())))
    }

    func hrvCalibratedScore(for deviation: Double) -> Int? {
        guard let linear = mappedScore(for: deviation) else { return nil }
        guard mappingVersion >= 3 else { return linear }
        let exponent = -hrvScoreSteepness * (Double(linear) - hrvScoreMidpoint)
        let calibrated = hrvScoreFloor + (100 - hrvScoreFloor) / (1 + exp(exponent))
        guard calibrated.isFinite else { return nil }
        return Int(min(100, max(1, calibrated.rounded())))
    }

    private enum CodingKeys: String, CodingKey {
        case baselineDays, heartRateFreshMinutes, hrvLifetimeHours, slope, center
        case pressureSlope, recoverySlope, mappingVersion, restingHRWeight, restingHRScaleFloor
        case hrvFilterEnabled, redJumpThreshold, redCooldownMinutes
        case hrvScoreFloor, hrvScoreMidpoint, hrvScoreSteepness
        case movementStepWindowMinutes, movementStepThreshold, useStepMovement
        case minIntervalMS, maxIntervalMS, minimumDuration, minimumPairs
        case minimumDays, minimumHRVRecords, minimumHRBins
        case hrvScaleFloor, hrScaleFloor, workoutRecoveryMinutes
        case defaultRMSSDMS, defaultHeartRateBPM, defaultHRVScale, defaultHeartRateScale
    }

    init(from decoder: Decoder) throws {
        self.init()
        let fields = try decoder.container(keyedBy: CodingKeys.self)
        baselineDays = try fields.decode(Int.self, forKey: .baselineDays)
        heartRateFreshMinutes = try fields.decode(Double.self, forKey: .heartRateFreshMinutes)
        hrvLifetimeHours = try fields.decode(Double.self, forKey: .hrvLifetimeHours)
        slope = try fields.decode(Double.self, forKey: .slope)
        pressureSlope = try fields.decodeIfPresent(Double.self, forKey: .pressureSlope) ?? pressureSlope
        recoverySlope = try fields.decodeIfPresent(Double.self, forKey: .recoverySlope) ?? recoverySlope
        mappingVersion = try fields.decodeIfPresent(Int.self, forKey: .mappingVersion) ?? 0
        hrvFilterEnabled = try fields.decodeIfPresent(Bool.self, forKey: .hrvFilterEnabled) ?? (mappingVersion < 2)
        redJumpThreshold = try fields.decodeIfPresent(Double.self, forKey: .redJumpThreshold) ?? redJumpThreshold
        redCooldownMinutes = try fields.decodeIfPresent(Double.self, forKey: .redCooldownMinutes) ?? redCooldownMinutes
        hrvScoreFloor = try fields.decodeIfPresent(Double.self, forKey: .hrvScoreFloor) ?? hrvScoreFloor
        hrvScoreMidpoint = try fields.decodeIfPresent(Double.self, forKey: .hrvScoreMidpoint) ?? hrvScoreMidpoint
        hrvScoreSteepness = try fields.decodeIfPresent(Double.self, forKey: .hrvScoreSteepness) ?? hrvScoreSteepness
        movementStepWindowMinutes = try fields.decodeIfPresent(Double.self, forKey: .movementStepWindowMinutes) ?? 10
        movementStepThreshold = try fields.decodeIfPresent(Double.self, forKey: .movementStepThreshold) ?? 8
        useStepMovement = try fields.decodeIfPresent(Bool.self, forKey: .useStepMovement) ?? true
        restingHRWeight = try fields.decodeIfPresent(Double.self, forKey: .restingHRWeight) ?? restingHRWeight
        restingHRScaleFloor = try fields.decodeIfPresent(Double.self, forKey: .restingHRScaleFloor) ?? restingHRScaleFloor
        center = try fields.decode(Double.self, forKey: .center)
        minIntervalMS = try fields.decode(Double.self, forKey: .minIntervalMS)
        maxIntervalMS = try fields.decode(Double.self, forKey: .maxIntervalMS)
        minimumDuration = try fields.decode(Double.self, forKey: .minimumDuration)
        minimumPairs = try fields.decode(Int.self, forKey: .minimumPairs)
        minimumDays = try fields.decode(Int.self, forKey: .minimumDays)
        minimumHRVRecords = try fields.decode(Int.self, forKey: .minimumHRVRecords)
        minimumHRBins = try fields.decode(Int.self, forKey: .minimumHRBins)
        hrvScaleFloor = try fields.decode(Double.self, forKey: .hrvScaleFloor)
        hrScaleFloor = try fields.decode(Double.self, forKey: .hrScaleFloor)
        workoutRecoveryMinutes = try fields.decode(Double.self, forKey: .workoutRecoveryMinutes)
        defaultRMSSDMS = try fields.decodeIfPresent(Double.self, forKey: .defaultRMSSDMS) ?? defaultRMSSDMS
        defaultHeartRateBPM = try fields.decodeIfPresent(Double.self, forKey: .defaultHeartRateBPM) ?? defaultHeartRateBPM
        defaultHRVScale = try fields.decodeIfPresent(Double.self, forKey: .defaultHRVScale) ?? defaultHRVScale
        defaultHeartRateScale = try fields.decodeIfPresent(Double.self, forKey: .defaultHeartRateScale) ?? defaultHeartRateScale
    }

    var validationError: String? {
        guard (7...30).contains(baselineDays), (1...60).contains(heartRateFreshMinutes),
              (0.25...12).contains(hrvLifetimeHours), (1...50).contains(slope),
              (1...30).contains(pressureSlope), (1...30).contains(recoverySlope),
              (0...3).contains(mappingVersion),
              (5...50).contains(redJumpThreshold), (0...180).contains(redCooldownMinutes),
              (1...20).contains(hrvScoreFloor), (20...80).contains(hrvScoreMidpoint),
              (0.03...0.4).contains(hrvScoreSteepness),
              (1...20).contains(movementStepWindowMinutes), (1...200).contains(movementStepThreshold),
              (0...1).contains(restingHRWeight), (3...20).contains(restingHRScaleFloor),
              (1...100).contains(center), (200...1000).contains(minIntervalMS),
              (1000...3000).contains(maxIntervalMS), minIntervalMS < maxIntervalMS,
              (10...300).contains(minimumDuration), (2...300).contains(minimumPairs),
              (1...baselineDays).contains(minimumDays), minimumHRVRecords > 0,
              minimumHRBins > 0, hrvScaleFloor.isFinite, hrvScaleFloor > 0,
              hrScaleFloor.isFinite, hrScaleFloor > 0,
              (0...120).contains(workoutRecoveryMinutes),
              (10...200).contains(defaultRMSSDMS), (40...120).contains(defaultHeartRateBPM),
              (0.1...2).contains(defaultHRVScale), (3...30).contains(defaultHeartRateScale) else { return "参数超出允许范围" }
        return nil
    }
}

struct ParameterVersion: Codable, Identifiable {
    var id: UUID = UUID()
    var createdAt: Date = Date()
    var parameters: ExperimentParameters
    var name: String
}

enum BodyState: String, Codable { case awake, asleep }
enum EstimateOrigin: String, Codable { case hrv, blended, heartRate, `default` }
struct BaselineSummary: Codable {
    var median: Double?
    var scale: Double?
    var days: Int
    var samples: Int
    var ready: Bool
}

struct HRVPoint: Identifiable, Codable {
    var id: String
    var date: Date
    var start: Date
    var sourceID: String
    var rawRMSSD: Double?
    var rmssd: Double?
    var validDuration: Double
    var pairCount: Int
    var state: BodyState
    var exclusionReasons: [String]
    var baselineEligible: Bool
    var assessment: HRVAssessment = .defaultReference
}

enum HRVAssessmentOrigin: String, Codable { case personal, provisional, `default` }

struct HRVAssessment: Codable {
    var score: Int
    var origin: HRVAssessmentOrigin
    var baseline: BaselineSummary

    static let defaultReference = HRVAssessment(
        score: 50,
        origin: .default,
        baseline: BaselineSummary(median: nil, scale: nil, days: 0, samples: 0, ready: false)
    )

    var level: String {
        switch score {
        case ...20: return "状态优秀"
        case ...60: return "状态一般"
        case ...80: return "注意压力"
        default: return "压力偏高"
        }
    }
}

struct PressurePoint: Identifiable, Codable {
    var id: String { "\(date.timeIntervalSince1970)-\(state.rawValue)" }
    var date: Date
    var score: Int?
    var origin: EstimateOrigin
    var state: BodyState
    var hrvDate: Date?
    var heartRateDate: Date?
    var rmssd: Double?
    var heartRate: Double?
    var hrvWeight: Double
    var hrvBaseline: BaselineSummary
    var heartRateBaseline: BaselineSummary
    var reasons: [String]
    var algorithmVersion: String
    var restingHeartRate: Double? = nil
    var restingHeartRateDate: Date? = nil
    var restingHeartRateBaseline: BaselineSummary? = nil
    var level: String {
        guard let score else { return "无可用估算" }
        switch score { case ...20: return "较低"; case ...60: return "一般"; case ...80: return "偏高"; default: return "高" }
    }
}

struct AnalysisResult: Codable {
    var hrv: [HRVPoint]
    var pressure: [PressurePoint]
    var current: PressurePoint
    var sleep: [ContextInterval]
}
